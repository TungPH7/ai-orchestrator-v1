import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';
import { renderAgent, renderAll, renderRules } from '../../lib/agents/render.mjs';
import { readRoster } from '../../lib/agents/roster.mjs';
import { readContract } from '../../lib/contract.mjs';
import { readGates } from '../../lib/quality/gates.mjs';
import { readMapping } from '../../lib/tracker/mapping.mjs';
import { CONTRACT_DIR, ROOT } from '../helpers/kit.mjs';

const sources = {
  roster: readRoster(join(ROOT, 'agents')),
  contract: readContract(CONTRACT_DIR),
  gates: readGates(join(ROOT, 'quality')),
  mapping: readMapping(join(ROOT, 'tracker')),
  prompts: Object.fromEntries(['pm', 'ba', 'ux', 'sa', 'fe-dev', 'be-dev', 'reviewer', 'security', 'qa', 'devops'].map((r) => [r, readFileSync(join(ROOT, 'agents', 'prompts', `${r}.md`), 'utf8')])),
  rules: readFileSync(join(ROOT, 'agents', 'rules.md'), 'utf8'),
};

const frontmatter = (text) => parse(text.slice(4, text.indexOf('\n---\n', 4)));
const body = (text) => text.slice(text.indexOf('\n---\n', 4) + 5);

test('the frontmatter of an agent: name, description, tools, model, effort and skills from the roster (spec 2.1, 6)', () => {
  const text = renderAgent('reviewer', sources);

  assert.match(text, /^---\n# Generated by scripts\/render-agents\.mjs from agents\/roster\.yaml, agents\/prompts\/reviewer\.md and the contract\. Do not edit\.\n/);
  assert.deepEqual(frontmatter(text), {
    name: 'reviewer',
    description: sources.roster.roles.reviewer.description,
    tools: 'Read, Glob, Grep, Bash, Write, mcp__atlassian__getJiraIssue, mcp__atlassian__searchJiraIssuesUsingJql, mcp__atlassian__executeRead',
    model: 'opus',
    effort: 'xhigh',
    skills: ['code-review-and-quality'],
  });
  assert.equal(frontmatter(renderAgent('pm', sources)).skills, undefined, 'no skills key without skills');
});

test('Jira tools follow the permissions, and MCP groups become the tools of their server', () => {
  const tools = frontmatter(renderAgent('fe-dev', sources)).tools.split(', ');

  for (const tool of ['getJiraIssue', 'editJiraIssue', 'addOrEditJiraIssueComment', 'transitionJiraIssue']) assert.ok(tools.includes(`mcp__atlassian__${tool}`), tool);
  assert.ok(!tools.includes('mcp__atlassian__createJiraIssue'));
  assert.equal(tools.filter((t) => t.startsWith('mcp__chrome-devtools__')).length, 31);
  assert.ok(tools.includes('mcp__chrome-devtools__list_console_messages'));
  assert.ok(!tools.some((t) => /executeWrite|executeDestructive|^Skill$|^Agent$|WebFetch|WebSearch/.test(t)), 'never granted');
  assert.ok(frontmatter(renderAgent('qa', sources)).tools.includes('mcp__atlassian__createJiraIssue'));
});

test('max_turns of the roster becomes maxTurns', () => {
  const roster = structuredClone(sources.roster);
  roster.roles.pm.max_turns = 30;
  assert.equal(frontmatter(renderAgent('pm', { ...sources, roster })).maxTurns, 30);
  assert.equal(frontmatter(renderAgent('pm', sources)).maxTurns, undefined);
});

test('the opening line names the role and its value in the Agent field', () => {
  assert.match(body(renderAgent('qa', sources)), /^\nYou are `qa`, the Tester\/QA Engineer of the SDLC contract\. Your value in the Agent field of Jira is "Tester\/QA Engineer"\.\n/);
});

test('the contract section: stages, artifacts, GitHub App, files and git (spec 2.1)', () => {
  const reviewer = body(renderAgent('reviewer', sources));
  assert.match(reviewer, /^## Contract$/m);
  assert.match(reviewer, /^- Stage `review` \(Review code và security\), with `security` and the human\. Input: PR có CI xanh\. Output: Báo cáo review\. Passes: Không còn finding Critical\/High; gate ③ `merge-approval`: Bạn approve PR\. Note: human duyệt sau reviewer và security\.$/m);
  assert.match(reviewer, /^- You create Báo cáo review \(`review-report`\) from `\.ai-orchestrator\/templates\/review-report\.md`, stored in GitHub: Review trên PR\.$/m);
  assert.match(reviewer, /^- GitHub: `node \.ai-orchestrator\/scripts\/ao-pr\.mjs review` with the review App \(`AO_REVIEW_APP`\)\. You never approve a PR\.$/m);
  assert.match(reviewer, /^- Files you may write: `\.ai\/\*\*`\. Git: read only \(status, log, show, diff, fetch and the other reading commands\)\.$/m);
  assert.match(body(renderAgent('ux', sources)), /^- GitHub: you have no App, so you do not open or comment on PRs\.$/m);
  assert.match(body(renderAgent('devops', sources)), /^- Files you may write: `\*\*`, but not the protected paths except `\.github\/workflows\/\*\*`\. Git: write\.$/m);
  assert.match(body(renderAgent('ba', sources)), /^- Stage `spec` \(Viết SPEC cho Epic\), which you lead, with `ux` and `sa`\. Input: Epic ở new\. Output: SPEC của Epic, Thiết kế màn hình\. Passes: gate ① `spec-approval`: Bạn duyệt SPEC của Epic\. Note: ux viết design khi Epic đụng tới giao diện\.$/m);
  assert.match(body(renderAgent('fe-dev', sources)), /^- Jira: read, edit, comment, transition\.$/m);
});

test('transitions are listed only for roles that may move items, with their names on Jira', () => {
  const qa = body(renderAgent('qa', sources));
  assert.match(qa, /^- Transitions you make: .*`pick-up` \(Pick up: Ready for QA → In QA\)/m);
  assert.match(qa, /`qa-fail` \(QA fail: In QA → In Progress\)/);
  assert.doesNotMatch(body(renderAgent('reviewer', sources)), /Transitions you make/, 'reviewer is an actor of request-changes but jira-sync makes it');
  const dev = body(renderAgent('fe-dev', sources));
  assert.match(dev, /`start` \(Start: Ready → In Progress\)/);
  assert.match(dev, /sub-task: `start`/i);
});

test('the hand-written prompt follows, without its HTML comments', () => {
  const text = renderAgent('security', sources);
  assert.ok(!text.includes('<!--'), 'no comment left');
  assert.ok(!text.includes('agency-agents'), 'the source note of the prompt is dropped');
  assert.match(text, /\n## How you work\n/);
  assert.ok(text.indexOf('## Contract') < text.indexOf('## How you work'));
});

test('rendering is stable: twice the same text, LF line ends, one final newline', () => {
  for (const role of Object.keys(sources.roster.roles)) {
    const text = renderAgent(role, sources);
    assert.equal(text, renderAgent(role, sources));
    assert.ok(!text.includes('\r') && text.endsWith('\n') && !text.endsWith('\n\n'), role);
  }
});

test('the rules file keeps agents/rules.md and fills each render marker from the contract (spec 2.6)', () => {
  const text = renderRules(sources);

  assert.match(text, /^<!-- Generated by scripts\/render-agents\.mjs from agents\/rules\.md and the contract\. Do not edit\. -->\n\n# ai-orchestrator rules\n/);
  assert.doesNotMatch(text, /render:/);
  assert.match(text, /Site `https:\/\/phunghuutung12b4\.atlassian\.net`, cloud id `58b36210-6e4d-421a-adf4-e74a4e23b069`, space `<KEY>`\./);
  assert.match(text, /^\| `fe-dev` \| Frontend Developer \|$/m);
  assert.equal(text.match(/^\| `[a-z-]+` \| .+ \|$/gm).filter((row) => !row.includes('templates/')).length, 10);
  assert.match(text, /When the same step fails 2 times in a row, flag the item "Needs you" and stop\./);
  assert.match(text, /^- Story and Task: `feature\/<KEY>-<slug>` from `develop`; QA on development\.$/m);
  assert.match(text, /^\| Production \| critical, high \| `main` \| staging, production \|$/m);
  assert.match(text, /^\| Thiết kế màn hình \| `\.ai-orchestrator\/templates\/design\.md` \| `ux` \| Git: `docs\/specs\/<EPIC-KEY>\/design\.md`; Git: `docs\/specs\/<EPIC-KEY>\/design\/` \(ảnh của màn hình kiểu Figma\) \|$/m);
  assert.match(text, /^ {2}- `\.github\/workflows\/\*\*`: only `devops`$/m);
  assert.match(text, /^ {2}- `\.claude\/\*\*`: no agent$/m);
  assert.match(renderRules({ ...sources, space: 'DEMO' }), /space `DEMO`/);
});

test('renderAll gives the ten agents and the rules file, by path under .claude/', () => {
  assert.deepEqual([...renderAll(sources).keys()].sort(), [
    ...Object.keys(sources.roster.roles).map((r) => `agents/${r}.md`),
    'rules/ai-orchestrator.md',
  ].sort());
});

test('the generated files of the kit are up to date (npm run agents:check)', () => {
  const result = spawnSync(process.execPath, [join(ROOT, 'scripts', 'render-agents.mjs'), '--check'], { cwd: ROOT, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.match(result.stdout, /11 files up to date/);
});
